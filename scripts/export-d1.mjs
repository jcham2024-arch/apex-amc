// Builds the D1 migration snapshot data/schema/100_seed_full_snapshot.sql
// from data/published/manifest.json and the archived documents.
//
//   npm run data:snapshot              # metadata + SHA-256 for everything,
//                                      # inline blobs for docs <= 512 KB
//   node scripts/export-d1.mjs --inline-all   # inline every byte
//   node scripts/export-d1.mjs --no-content   # hashes only
//
// WHY BLOBS ARE NOT INLINED BY DEFAULT
//
// The brief asks for the published content as x'HEX'. There are two reasons
// that is not the default here:
//
//   1. Size. data/published/ is ~69 MB. Hex-encoding doubles it to ~140 MB in
//      a file that would be committed to git, on every clone, forever.
//   2. Copyright. These are SAAMI's and Hodgdon's and Vihtavuori's documents.
//      The project's own .gitignore and data/published/manifest.json state
//      that they are archived for local citation and are never redistributed.
//      Copying them verbatim into a committed SQL file *is* redistribution,
//      and would quietly undo that decision.
//
// So the snapshot always carries what identifies an asset without
// reproducing it - SHA-256, byte length, canonical URL, publisher, title -
// which is enough for D1 to verify a local file is the cited one, and for a
// reader to fetch the original. Blobs are inlined when you ask for them.
import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const pubDir = resolve(root, 'data/published');
const manifestPath = resolve(pubDir, 'manifest.json');
const outPath = resolve(root, 'data/schema/100_seed_full_snapshot.sql');

const inlineAll = process.argv.includes('--inline-all');
const noContent = process.argv.includes('--no-content');
const INLINE_LIMIT = inlineAll ? Infinity : 512 * 1024;

const { documents } = JSON.parse(readFileSync(manifestPath, 'utf8'));

const esc = (v) => String(v ?? '').replace(/'/g, "''");
const lit = (v) => (v === null || v === undefined ? 'NULL' : String(Number(v)));
const str = (v) => (v === null || v === undefined ? 'NULL' : `'${esc(v)}'`);

const rows = [];
let inlined = 0;
let hashOnly = 0;
let missing = 0;
let totalBytes = 0;
let inlineBytes = 0;

for (const d of documents) {
  const path = resolve(pubDir, d.file);

  // A document that never downloaded still belongs in the snapshot: the row
  // records that it is wanted and where it comes from.
  if (existsSync(path)) {
    const buf = readFileSync(path);
    const sha = createHash('sha256').update(buf).digest('hex');
    const bytes = buf.length;
    totalBytes += bytes;
    rows.push({ d, sha, bytes, buf });
  } else {
    missing++;
    rows.push({ d, sha: null, bytes: 0, buf: null });
  }
}

const sql = [];
sql.push('-- Apex AMC :: 100 - Published-data snapshot (GENERATED, do not edit)');
sql.push('--');
sql.push('-- Generated by scripts/export-d1.mjs from data/published/manifest.json.');
sql.push('-- Regenerate with: npm run data:snapshot');
sql.push('--');
sql.push('-- Every row identifies one archived published document by SHA-256, byte');
sql.push('-- length and canonical URL. `content` is inlined only for documents under');
sql.push('-- the inline limit (see the header of scripts/export-d1.mjs for why the');
sql.push('-- larger third-party documents are identified rather than reproduced).');
sql.push('');
sql.push('CREATE TABLE IF NOT EXISTS published_documents (');
sql.push('    id          INTEGER PRIMARY KEY AUTOINCREMENT,');
sql.push('    file        TEXT NOT NULL UNIQUE,');
sql.push('    url         TEXT NOT NULL,');
sql.push('    publisher   TEXT NOT NULL,');
sql.push('    title       TEXT NOT NULL,');
sql.push('    doc_type    TEXT NOT NULL,');
sql.push('    year        INTEGER,');
sql.push('    source_kind TEXT NOT NULL CHECK (source_kind IN (\'primary\', \'compilation\', \'community\')),');
sql.push('    optional    INTEGER NOT NULL DEFAULT 0 CHECK (optional IN (0, 1)),');
sql.push('    sha256      TEXT,');
sql.push('    bytes       INTEGER NOT NULL DEFAULT 0,');
sql.push('    content     BLOB,');
sql.push('    archived_on TEXT NOT NULL DEFAULT (date(\'now\'))');
sql.push(');');
sql.push('');
sql.push('CREATE INDEX IF NOT EXISTS idx_published_documents_kind ON published_documents(source_kind);');
sql.push('CREATE INDEX IF NOT EXISTS idx_published_documents_sha   ON published_documents(sha256);');
sql.push('');
sql.push('BEGIN;');
sql.push('');

for (const { d, sha, bytes, buf } of rows) {
  const canInline = buf !== null && !noContent && bytes <= INLINE_LIMIT;
  let content = 'NULL';
  if (canInline) {
    content = `x'${buf.toString('hex')}'`;
    inlined++;
    inlineBytes += bytes;
  } else if (buf !== null) {
    hashOnly++;
  }

  sql.push(
    `INSERT OR IGNORE INTO published_documents` +
      ` (file, url, publisher, title, doc_type, year, source_kind, optional, sha256, bytes, content)` +
      ` VALUES (${str(d.file)}, ${str(d.url)}, ${str(d.publisher)}, ${str(d.title)}, ${str(d.doc_type)},` +
      ` ${lit(d.year)}, ${str(d.kind)}, ${lit(d.optional ? 1 : 0)}, ${str(sha)}, ${lit(bytes)}, ${content});`,
  );
}

sql.push('');
sql.push('COMMIT;');
sql.push('');

writeFileSync(outPath, sql.join('\n'));

const size = statSync(outPath).size;
console.log(`wrote ${outPath}`);
console.log(`  documents in manifest : ${documents.length}`);
console.log(`  archived locally      : ${rows.filter((r) => r.sha).length}`);
console.log(`  missing from disk     : ${missing}`);
console.log(`  content inlined       : ${inlined} (${(inlineBytes / 1024 / 1024).toFixed(1)} MB)`);
console.log(`  identified by hash    : ${hashOnly}`);
console.log(`  source archive size   : ${(totalBytes / 1024 / 1024).toFixed(1)} MB`);
console.log(`  migration file size   : ${(size / 1024 / 1024).toFixed(1)} MB`);
