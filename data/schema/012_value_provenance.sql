-- Apex AMC :: 012 - Field-level value provenance
--
-- The problem this solves.
--
-- `docs/DATA-MODEL.md` rule 1 says provenance is mandatory and
-- `data/incoming/powders.md` rule 1 says "no invented values - a cell is left
-- EMPTY rather than guessed". Both are right, and together they create a gap:
--
--   * A value that genuinely does not exist anywhere should stay NULL. Correct.
--   * A value that DOES exist in the real world but which no archived source
--     covers is currently indistinguishable from the first case. It just looks
--     like an empty cell, and the next person cannot tell "nobody knows this"
--     from "nobody has looked yet".
--
-- That ambiguity is the expensive kind. 12 of 21 columns in
-- data/seeds/cartridge_specs.csv are 100% empty, and every one of them is a
-- real, published SAAMI/CIP dimension that simply has not been transcribed
-- yet. Nothing in the data distinguishes "transcription not started" from
-- "this number does not exist".
--
-- So: NULL remains the correct answer for a value that does not exist. But a
-- value that CAN be filled in - by calculation, by cross-referencing a related
-- published figure, or by reading a community report - may be recorded, as
-- long as it carries its own annotation saying exactly that, and saying how.
--
-- This is the same three-tier ladder the domain package already enforces in
-- packages/ballistics-core/src/provenance/Source.ts (`published`, `derived`,
-- `estimated`), applied to tabular seed data rather than to code constants.
-- The tier names are deliberately identical so there is one idea in the
-- project, not two.
--
-- WHAT THIS IS NOT
-- ---------------
-- This is NOT a loophole for filling cells with plausible numbers. Three
-- structural guarantees keep it honest:
--
--   1. A value CANNOT be written into a real column without a matching row
--      here. `check-seeds.mjs` refuses the write otherwise. There is no way
--      to smuggle a number past this table.
--   2. `derived` and `estimated` rows REQUIRE a method or a reasoning string.
--      An empty one fails the build, mirroring the UnverifiedValueError
--      thrown by the `derived()`/`estimated()` constructors in Source.ts.
--   3. `estimated` is explicitly a "we do not know this" marker. It exists so
--      a user asking "where does this come from?" gets an honest answer
--      instead of a confident fabrication. The UI must render these
--      differently - that is the entire point of recording them.
--

-- ---------------------------------------------------------------------------
-- One row per (entity, field) that is NOT a plain published transcription.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS value_provenance (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,

    -- What the value belongs to. Deliberately slug + type rather than three
    -- nullable FKs: the same annotation logic must cover cartridges, bullets,
    -- powders and manufacturers, and a cartridge and a bullet can
    -- legitimately share a slug.
    entity_type  TEXT NOT NULL
                 CHECK (entity_type IN ('cartridge', 'bullet', 'powder',
                                        'manufacturer', 'burn_rate_chart')),
    entity_slug  TEXT NOT NULL,

    -- The single column this annotates, e.g. 'case_length_max_in'.
    field_name   TEXT NOT NULL,

    -- Which tier. Identical vocabulary to Source.ts:
    --   published  transcribed from a standard/manual; needs a source_id
    --   derived    computed from published values; needs `method`
    --   estimated  no published value exists; needs `reasoning`
    --   community  promoted from forum consensus; needs `source_url`
    tier         TEXT NOT NULL
                 CHECK (tier IN ('published', 'derived', 'estimated', 'community')),

    -- The value as recorded in the parent table, denormalised so the audit
    -- trail survives the parent row being regenerated by a re-extract.
    value        REAL,
    text_value   TEXT,
    unit         TEXT,

    -- For `published` and `derived`: which standards/manuals.
    source_id    INTEGER REFERENCES sources(id),

    -- For `derived`: the formula or procedure, spelled out enough that
    -- somebody else could redo it. REQUIRED when tier='derived'.
    method       TEXT,

    -- For `estimated` and `community`: why the value is not from an official
    -- source, and what it was inferred from. REQUIRED for both.
    reasoning    TEXT,

    -- Free-text citation for community/tertiary work that has no `sources`
    -- row: forum name, thread URL, measurement setup. Deliberately NOT a
    -- foreign key, because a forum is not a published source and forcing it
    -- into `sources` would launder it as one.
    source_url   TEXT,

    -- For `community`: how dangerous it is to be wrong. Mirrors 011.
    safety_risk  TEXT
                 CHECK (safety_risk IN ('low', 'medium', 'high')),

    -- Agreement among independent reports, for `community` rows.
    -- 1 = one person's say-so; 5 = multiple independent sources concur.
    corroboration INTEGER CHECK (corroboration BETWEEN 1 AND 5),

    -- Who signed off, and when. A derived value is an editorial act.
    reviewed_by  TEXT,
    reviewed_on  TEXT,

    notes        TEXT,

    -- One annotation per (entity, field). Re-annotating replaces the old row
    -- rather than accumulating history, which matches how the CSVs are
    -- regenerated. Record the history in `notes`.
    UNIQUE (entity_type, entity_slug, field_name)
);

CREATE INDEX IF NOT EXISTS idx_vp_entity  ON value_provenance(entity_type, entity_slug);
CREATE INDEX IF NOT EXISTS idx_vp_tier    ON value_provenance(tier);
CREATE INDEX IF NOT EXISTS idx_vp_field   ON value_provenance(field_name);

-- ---------------------------------------------------------------------------
-- Reporting views
-- ---------------------------------------------------------------------------

-- The work queue, ordered by how much it matters. An editor opening this
-- should see the dangerous unknowns first, not the easy ones.
CREATE VIEW IF NOT EXISTS provenance_worklist AS
SELECT
    entity_type, entity_slug, field_name, tier, value, unit,
    method, reasoning, safety_risk, corroboration
FROM value_provenance
ORDER BY
    CASE tier
        WHEN 'community' THEN 0   -- highest risk, resolve or delete first
        WHEN 'estimated' THEN 1
        WHEN 'derived'   THEN 2
        ELSE 3
    END,
    entity_type, entity_slug, field_name;

-- How much of each table rests on something other than a published figure.
-- This is the number to watch: it should only ever go DOWN as real sources
-- are found.
CREATE VIEW IF NOT EXISTS provenance_summary AS
SELECT
    entity_type,
    tier,
    COUNT(*)                       AS n,
    SUM(CASE WHEN safety_risk = 'high' THEN 1 ELSE 0 END) AS high_risk
FROM value_provenance
GROUP BY entity_type, tier;

-- Community-sourced values sitting in an official column. Always empty in a
-- healthy database - every row here is a decision someone made deliberately
-- and should be able to justify out loud.
CREATE VIEW IF NOT EXISTS provenance_community_promoted AS
SELECT entity_type, entity_slug, field_name, value, unit,
       source_url, safety_risk, corroboration, reasoning
FROM value_provenance
WHERE tier = 'community'
ORDER BY CASE safety_risk WHEN 'high' THEN 0 WHEN 'medium' THEN 1 ELSE 2 END;

-- A value whose recorded number disagrees with what the parent table now holds
-- means the parent was regenerated (a re-extract, a hand edit) without updating
-- the annotation. The number in the CSV and the number the site would show have
-- diverged, which is exactly the silent drift this layer exists to prevent.
-- `check-seeds.mjs` fails the build on any row this view returns.
--
-- SCOPE: only the cartridge columns that actually exist on the `cartridges`
-- table are cross-checked. `cartridges` has saami_max_psi and federal_max_psi
-- (001) plus the CIP/dimension columns added by 009 - it has no saami_max_cup
-- column, because a CUP figure is a different measurement method rather than
-- another attribute of the same limit, so CUP values live in
-- cartridge_pressure_references and are audited by the disputes view instead.
--
-- An annotation for a field with no matching parent column is simply not
-- drift-checked; it still requires a tier justification, so it cannot be used to
-- smuggle an unsourced number into a column that does not exist.
CREATE VIEW IF NOT EXISTS provenance_value_drift AS
SELECT
    vp.entity_type, vp.entity_slug, vp.field_name,
    vp.value AS annotated_value,
    CASE vp.field_name
        WHEN 'saami_max_psi'      THEN c.saami_max_psi
        WHEN 'federal_max_psi'    THEN c.federal_max_psi
        WHEN 'cip_max_bar'        THEN c.cip_max_bar
        WHEN 'case_length_max_in' THEN c.case_length_max_in
        WHEN 'max_col_in'         THEN c.max_col_in
        WHEN 'capacity_gr_h2o'    THEN c.capacity_gr_h2o
        WHEN 'bullet_dia_in'      THEN c.bullet_dia_in
        WHEN 'typical_twist_in'   THEN c.typical_twist_in
        WHEN 'rim_dia_in'         THEN c.rim_dia_in
        WHEN 'head_dia_in'        THEN c.head_dia_in
        WHEN 'primer_type'        THEN NULL
    END AS current_value,
    vp.tier
FROM value_provenance vp
JOIN cartridges c
  ON vp.entity_type = 'cartridge'
 AND vp.entity_slug = c.slug
WHERE vp.value IS NOT NULL
  AND vp.field_name IN (
        'saami_max_psi', 'federal_max_psi', 'cip_max_bar',
        'case_length_max_in', 'max_col_in', 'capacity_gr_h2o',
        'bullet_dia_in', 'typical_twist_in', 'rim_dia_in', 'head_dia_in')
  AND ABS(vp.value - CASE vp.field_name
        WHEN 'saami_max_psi'      THEN c.saami_max_psi
        WHEN 'federal_max_psi'    THEN c.federal_max_psi
        WHEN 'cip_max_bar'        THEN c.cip_max_bar
        WHEN 'case_length_max_in' THEN c.case_length_max_in
        WHEN 'max_col_in'         THEN c.max_col_in
        WHEN 'capacity_gr_h2o'    THEN c.capacity_gr_h2o
        WHEN 'bullet_dia_in'      THEN c.bullet_dia_in
        WHEN 'typical_twist_in'   THEN c.typical_twist_in
        WHEN 'rim_dia_in'         THEN c.rim_dia_in
        WHEN 'head_dia_in'        THEN c.head_dia_in
      END) > 0.000001;
